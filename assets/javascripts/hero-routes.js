/* CoPTER hero routes: in-browser UAV route planning over each place's terrain.

   Shared by the home page hero and the route lab (drafts/terrain.md).
   Each planner produces one or more routes and an optional "thinking"
   animation, then a shared flight. Coverage routes reveal the dimmed map
   through fading sensor circles:
     lawnmower  parallel passes with overlapping views
     square     search-and-rescue expanding square from a datum
     contour    the land's own contour lines, chosen so their views overlap
     partition  three drones, k-means zones, each sweeping its own
     explore    greedy exploration of the most rugged unseen ground
   Point-to-point routes show the whole map:
     astar      energy-aware A* to a goal beyond the high ground
     rrt        random tree around a no-go zone above an altitude ceiling

   Data per place (generated by tools/terrain_preview.py):
     assets/terrain/<slug>.svg       contour layer
     assets/terrain/grid/<slug>.json coarse elevation grid for planning */
(function () {
  "use strict";
  var W = 1200, H = 560, NS = "http://www.w3.org/2000/svg";
  var HOME = { x: 560, y: 520 };
  // The part of the 1200 × 560 scene actually on screen. The SVG scales to cover
  // its box ("slice"), cropping top and bottom on wide windows and the sides on
  // narrow ones, so take-off, survey areas and goals are placed inside this.
  var VIEW = { x0: 0, y0: 0, x1: W, y1: H };
  function vx(f) { return VIEW.x0 + f * (VIEW.x1 - VIEW.x0); }
  function vy(f) { return VIEW.y0 + f * (VIEW.y1 - VIEW.y0); }
  // Where routes go across the screen. On desktop they keep to the right,
  // clear of the heading (fractions from 0.4 to 0.95). On narrow screens the
  // heading spans the full width anyway, so the same range spreads across it.
  var NARROW = false;
  function ax(f) { return NARROW ? vx(0.06 + 0.88 * Math.max(0, Math.min(1, (f - 0.4) / 0.55))) : vx(f); }
  function inView(p, m) { m = m || 0; return p.x >= VIEW.x0 + m && p.x <= VIEW.x1 - m && p.y >= VIEW.y0 + m && p.y <= VIEW.y1 - m; }
  function setView(svg) {
    var r = svg.getBoundingClientRect();
    if (r.width && r.height) {
      var scale = Math.max(r.width / W, r.height / H), vw = r.width / scale, vh = r.height / scale;
      VIEW = { x0: (W - vw) / 2, x1: (W + vw) / 2, y0: (H - vh) / 2, y1: (H + vh) / 2 };
      NARROW = r.width < 720;
    }
    HOME = { x: Math.max(VIEW.x0 + 40, Math.min(VIEW.x1 - 40, 560)), y: VIEW.y1 - 40 }; // take-off near the visible bottom
  }
  var reduced = window.matchMedia && window.matchMedia("(prefers-reduced-motion: reduce)").matches;

  var ALGOS = {
    lawnmower: { label: "Lawnmower", coverage: true, text: "The classic survey: parallel passes back and forth, spaced so the sensor's view overlaps the last pass. The map is revealed where the sensor has looked." },
    square: { label: "Expanding square", coverage: true, text: "The standard search-and-rescue pattern. From a datum point, the drone spirals outwards in square legs that grow by one track width every two turns, revealing the map as it goes." },
    contour: { label: "Contour survey", coverage: true, text: "The drone flies the land's own contour lines a section at a time, holding a constant height above the ground on each, and moves on to the nearest section next. Lines are chosen so their views overlap." },
    partition: { label: "Multi-drone partition", coverage: true, text: "Three drones split the area into zones grown from random seeds (k-means), then each sweeps its own zone at the same time, revealing the map together." },
    explore: { label: "Exploration", coverage: true, text: "The drone keeps heading for the most rugged unexplored ground within reach. Contours appear only where its sensor has looked." },
    astar: { label: "A* energy-aware route", coverage: false, text: "The goal is beyond the high ground. A* searches outwards from take-off, cheapest first, where climbing and descending both cost energy, so it weighs going over against going round." },
    rrt: { label: "RRT (random tree)", coverage: false, text: "The drone must stay below an altitude ceiling, such as a cloud base, so the shaded high ground is off limits. A random tree grows around it until a branch reaches the goal; the rest of the tree fades and the drone flies a smoothed version of that branch." },
  };
  function pick(list) { return list[Math.floor(Math.random() * list.length)]; }

  // ── helpers ─────────────────────────────────────────────────────────────
  function el(name, attrs, parent) {
    var e = document.createElementNS(NS, name);
    for (var k in attrs) e.setAttribute(k, attrs[k]);
    if (parent) parent.appendChild(e);
    return e;
  }
  function rand(seed) { // small deterministic PRNG (mulberry32)
    return function () {
      seed |= 0; seed = (seed + 0x6d2b79f5) | 0;
      var t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
      t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
  }
  function dist(a, b) { return Math.hypot(a.x - b.x, a.y - b.y); }

  // ── terrain grid ────────────────────────────────────────────────────────
  function Terrain(g) {
    var bytes = Uint8Array.from(atob(g.data), function (c) { return c.charCodeAt(0); });
    this.w = g.w; this.h = g.h; this.cell = W / g.w; // viewBox units per cell
    this.mPerUnit = (g.km * 1000) / W; // metres per viewBox unit
    this.z = new Float32Array(bytes.length);
    this.sea = new Uint8Array(bytes.length);
    for (var i = 0; i < bytes.length; i++) {
      this.sea[i] = bytes[i] === 0 ? 1 : 0;
      this.z[i] = bytes[i] === 0 ? 0 : g.lo + ((bytes[i] - 1) / 254) * (g.hi - g.lo);
    }
  }
  Terrain.prototype.idx = function (gx, gy) { return gy * this.w + gx; };
  Terrain.prototype.toCell = function (p) {
    return { gx: Math.max(0, Math.min(this.w - 1, Math.floor(p.x / this.cell))),
             gy: Math.max(0, Math.min(this.h - 1, Math.floor(p.y / this.cell))) };
  };
  Terrain.prototype.centre = function (gx, gy) { return { x: (gx + 0.5) * this.cell, y: (gy + 0.5) * this.cell }; };
  Terrain.prototype.at = function (p) { var c = this.toCell(p); return this.z[this.idx(c.gx, c.gy)]; };
  Terrain.prototype.highPoint = function (x0) { // highest cell right of x0
    var best = -1, bi = 0;
    var gy0 = Math.max(1, Math.ceil(VIEW.y0 / this.cell)), gy1 = Math.min(this.h - 1, Math.floor(VIEW.y1 / this.cell));
    var gx1 = Math.min(this.w - 1, Math.floor(VIEW.x1 / this.cell));
    for (var gy = gy0; gy < gy1; gy++) // only what's on screen
      for (var gx = Math.ceil(x0 / this.cell); gx < gx1; gx++) {
        var i = this.idx(gx, gy);
        if (this.z[i] > best) { best = this.z[i]; bi = i; }
      }
    return this.centre(bi % this.w, Math.floor(bi / this.w));
  };

  // ── planners: each returns { route or routes, reveal + spacing (coverage), search, goal, ... } ──

  // Sensor circles for the coverage routes. With radius 0.62 × pass spacing and a
  // look every 0.7 × pass spacing, the band each pass covers is still at least
  // one pass wide, so passes overlap with no gaps, using as few circles as possible.
  function sensor(gap) { return { reveal: 0.62 * gap, spacing: 0.7 * gap }; }
  function withSensor(plan, gap) { var s = sensor(gap); plan.reveal = s.reveal; plan.spacing = s.spacing; return plan; }

  // Round off a polyline's corners with short curves (radius up to r, and at most half of either leg), so
  // the drone banks round turns instead of stopping dead. leg[i] is the original leg each new point ends,
  // for planners whose sensor rules count legs.
  function roundCorners(pts, r) {
    var out = [pts[0]], leg = [0];
    for (var i = 1; i < pts.length - 1; i++) {
      var a = pts[i - 1], b = pts[i], c = pts[i + 1], ab = dist(a, b), bc = dist(b, c);
      var k = Math.min(r, ab / 2, bc / 2);
      if (k < 2) { out.push(b); leg.push(i); continue; }
      var p1 = { x: b.x + (a.x - b.x) * k / ab, y: b.y + (a.y - b.y) * k / ab }, p2 = { x: b.x + (c.x - b.x) * k / bc, y: b.y + (c.y - b.y) * k / bc };
      out.push(p1); leg.push(i);
      for (var j = 1; j <= 6; j++) {
        var u = j / 6, w = 1 - u;
        out.push({ x: w * w * p1.x + 2 * w * u * b.x + u * u * p2.x, y: w * w * p1.y + 2 * w * u * b.y + u * u * p2.y }); leg.push(i + 1);
      }
    }
    out.push(pts[pts.length - 1]); leg.push(pts.length - 1);
    return { pts: out, leg: leg };
  }

  function planLawnmower(t) {
    var x0 = ax(0.52), x1 = ax(0.95), y0 = vy(0.16), y1 = vy(0.9), gap = 80;
    var pts = [HOME];
    for (var y = y0, i = 0; y <= y1; y += gap, i++) pts.push({ x: i % 2 ? x1 : x0, y: y }, { x: i % 2 ? x0 : x1, y: y });
    pts.push(HOME);
    pts = roundCorners(pts, gap / 2).pts; // each turn between passes becomes a smooth U
    return withSensor({ route: pts, survey: function (p) { return p.x >= x0 - 1 && p.x <= x1 + 1 && p.y >= y0 - 1 && p.y <= y1 + 1; } }, gap);
  }

  function astar(t, start, goal, climbWeight, descentWeight) {
    var N = t.w * t.h, g = new Float64Array(N).fill(Infinity), came = new Int32Array(N).fill(-1);
    var closed = new Uint8Array(N), order = [];
    var s = t.toCell(start), e = t.toCell(goal), si = t.idx(s.gx, s.gy), ei = t.idx(e.gx, e.gy);
    var heap = [], cellM = t.cell * t.mPerUnit;
    function push(i, f) { heap.push([f, i]); var c = heap.length - 1; while (c) { var p = (c - 1) >> 1; if (heap[p][0] <= heap[c][0]) break; var tmp = heap[p]; heap[p] = heap[c]; heap[c] = tmp; c = p; } }
    function pop() { var top = heap[0], last = heap.pop(); if (heap.length) { heap[0] = last; var c = 0; for (;;) { var l = 2 * c + 1, r = l + 1, m = c; if (l < heap.length && heap[l][0] < heap[m][0]) m = l; if (r < heap.length && heap[r][0] < heap[m][0]) m = r; if (m === c) break; var tmp = heap[m]; heap[m] = heap[c]; heap[c] = tmp; c = m; } } return top; }
    function h(i) { return Math.hypot(i % t.w - e.gx, Math.floor(i / t.w) - e.gy) * cellM; }
    g[si] = 0; push(si, h(si));
    while (heap.length) {
      var i = pop()[1];
      if (closed[i]) continue;
      closed[i] = 1; order.push(i);
      if (i === ei) break;
      var x = i % t.w, y = Math.floor(i / t.w);
      for (var dy = -1; dy <= 1; dy++) for (var dx = -1; dx <= 1; dx++) {
        if (!dx && !dy) continue;
        var nx = x + dx, ny = y + dy;
        if (nx < 0 || ny < 0 || nx >= t.w || ny >= t.h || !inView(t.centre(nx, ny), 4)) continue; // stay on screen
        var j = t.idx(nx, ny); if (closed[j]) continue;
        var d = Math.hypot(dx, dy) * cellM, dz = t.z[j] - t.z[i];
        var cost = g[i] + d + climbWeight * Math.max(0, dz) + descentWeight * Math.max(0, -dz); // height changes cost energy
        if (cost < g[j]) { g[j] = cost; came[j] = i; push(j, cost + h(j)); }
      }
    }
    var path = [], c = ei;
    while (c !== -1) { path.push(t.centre(c % t.w, Math.floor(c / t.w))); c = came[c]; }
    path.reverse();
    path[0] = start; path[path.length - 1] = goal;
    return { path: path, order: order };
  }

  // Straighten a grid path: skip ahead wherever a direct line climbs no more than
  // the steps it replaces (string pulling), then round the corners (Chaikin).
  function smoothPath(t, path, climbWeight) {
    function climb(a, b) {
      var k = Math.max(2, Math.ceil(dist(a, b) / (t.cell / 2))), prev = t.at(a), up = 0;
      for (var j = 1; j <= k; j++) { var z = t.at({ x: a.x + ((b.x - a.x) * j) / k, y: a.y + ((b.y - a.y) * j) / k }); up += Math.max(0, z - prev); prev = z; }
      return up;
    }
    var out = [path[0]], i = 0;
    while (i < path.length - 1) {
      var j = path.length - 1;
      for (; j > i + 1; j--) {
        var direct = dist(path[i], path[j]) * t.mPerUnit + climbWeight * climb(path[i], path[j]), along = 0;
        for (var k = i; k < j; k++) along += dist(path[k], path[k + 1]) * t.mPerUnit + climbWeight * climb(path[k], path[k + 1]);
        if (direct <= along * 1.02) break;
      }
      out.push(path[j]); i = j;
    }
    for (var pass = 0; pass < 2; pass++) {
      var r = [out[0]];
      for (var m = 0; m < out.length - 1; m++) {
        var a = out[m], b = out[m + 1];
        r.push({ x: 0.75 * a.x + 0.25 * b.x, y: 0.75 * a.y + 0.25 * b.y }, { x: 0.25 * a.x + 0.75 * b.x, y: 0.25 * a.y + 0.75 * b.y });
      }
      r.push(out[out.length - 1]); out = r;
    }
    return out;
  }

  // A goal beyond the high ground, so the straight line crosses it and the
  // planner has a real choice between over and around.
  function farGoal(t) {
    var hp = t.highPoint(ax(0.5));
    var g = { x: hp.x + (hp.x - HOME.x) * 0.9, y: hp.y + (hp.y - HOME.y) * 0.9 };
    g = { x: Math.max(VIEW.x0 + 30, Math.min(VIEW.x1 - 30, g.x)), y: Math.max(VIEW.y0 + 30, Math.min(VIEW.y1 - 30, g.y)) };
    return dist(g, HOME) < 300 ? { x: VIEW.x1 - 60, y: VIEW.y0 + 60 } : g;
  }

  // Length and total climb and descent along a route, for the comparison line
  function stats(t, pts) {
    var len = 0, up = 0, down = 0;
    for (var i = 1; i < pts.length; i++) {
      var a = pts[i - 1], b = pts[i], n = Math.max(1, Math.ceil(dist(a, b) / (t.cell / 2))), prev = t.at(a);
      len += dist(a, b);
      for (var k = 1; k <= n; k++) {
        var z = t.at({ x: a.x + ((b.x - a.x) * k) / n, y: a.y + ((b.y - a.y) * k) / n });
        if (z > prev) up += z - prev; else down += prev - z;
        prev = z;
      }
    }
    return { km: (len * t.mPerUnit) / 1000, up: up, down: down };
  }
  function compare(t, route, goal) {
    var a = stats(t, route), b = stats(t, [HOME, goal]);
    function f(s) { return s.km.toFixed(1) + " km, " + Math.round(s.up) + " m of climbing"; }
    return "This route: " + f(a) + ". Flying straight there: " + f(b) + ".";
  }

  function planAstar(t) {
    var goal = farGoal(t);
    var r = astar(t, HOME, goal, 20, 6);
    r.path = smoothPath(t, r.path, 20);
    var cells = r.order.map(function (i) { return t.centre(i % t.w, Math.floor(i / t.w)); });
    return { route: r.path, goal: goal, shots: false, note: compare(t, r.path, goal),
             search: { kind: "cells", items: cells } };
  }

  function planRRT(t) {
    // An altitude ceiling (think cloud base or an airspace limit) set from this
    // terrain: ground above it is a no-go zone the tree must grow around.
    var land = []; for (var i = 0; i < t.z.length; i++) if (!t.sea[i]) land.push(t.z[i]);
    land.sort(function (a, b) { return a - b; });
    var lo = land[0] || 0, hi = land[land.length - 1] || 1, goal = farGoal(t), plan;
    var floorZ = Math.max(t.at(HOME), t.at(goal)) + 0.04 * (hi - lo); // take-off and goal must be clear
    var top = 0; // highest ground on the direct line: the ceiling must sit below it, or there's nothing to avoid
    for (var k = 0; k <= 200; k++) top = Math.max(top, t.at({ x: HOME.x + ((goal.x - HOME.x) * k) / 200, y: HOME.y + ((goal.y - HOME.y) * k) / 200 }));
    for (var q = 0.6, n = 0; n < 5; q += 0.08, n++) {
      var ceiling = Math.max(floorZ, land[Math.floor(land.length * Math.min(q, 0.99))]);
      if (top > floorZ) ceiling = Math.min(ceiling, floorZ + (0.5 + 0.1 * n) * (top - floorZ));
      if ((plan = growRRT(t, goal, ceiling))) {
        var nogo = [];
        for (var c = 0; c < t.z.length; c++) if (t.z[c] > ceiling) nogo.push(t.centre(c % t.w, Math.floor(c / t.w)));
        plan.nogo = nogo; plan.shots = false;
        plan.note = "Ceiling " + Math.round(ceiling) + " m. " + compare(t, plan.route, goal);
        return plan;
      }
    }
    return { route: [HOME, goal], goal: goal, shots: false };
  }

  function growRRT(t, goal, ceiling) {
    var rnd = rand((Math.random() * 1e9) | 0), step = 26, max = 2500;
    var nx = new Float32Array(max + 2), ny = new Float32Array(max + 2), parent = new Int32Array(max + 2), n = 0, edges = [];
    function add(x, y, p) { nx[n] = x; ny[n] = y; parent[n] = p; return n++; }
    function ok(a, b) { // the whole edge must stay below the ceiling
      var k = Math.max(2, Math.ceil(dist(a, b) / (t.cell / 2)));
      for (var j = 0; j <= k; j++) if (t.at({ x: a.x + ((b.x - a.x) * j) / k, y: a.y + ((b.y - a.y) * j) / k }) > ceiling) return false;
      return true;
    }
    add(HOME.x, HOME.y, -1);
    var found = -1;
    for (var it = 0; it < 6000 && n < max && found < 0; it++) {
      var s = rnd() < 0.1 ? goal : { x: vx(rnd()), y: vy(rnd()) };
      var best = 0, bd = Infinity; // linear nearest-node scan over typed arrays: fast at this size
      for (var i = 0; i < n; i++) { var d = (nx[i] - s.x) * (nx[i] - s.x) + (ny[i] - s.y) * (ny[i] - s.y); if (d < bd) { bd = d; best = i; } }
      bd = Math.sqrt(bd); if (bd < 1) continue;
      var a = { x: nx[best], y: ny[best] }, f = Math.min(1, step / bd), b = { x: a.x + (s.x - a.x) * f, y: a.y + (s.y - a.y) * f };
      if (!inView(b) || !ok(a, b)) continue;
      var bi = add(b.x, b.y, best); edges.push([a, b]);
      if (dist(b, goal) < step && ok(b, goal)) { found = add(goal.x, goal.y, bi); edges.push([b, goal]); }
    }
    if (found < 0) return null;
    var path = [];
    for (var c = found; c !== -1; c = parent[c]) path.push({ x: nx[c], y: ny[c] });
    path.reverse();
    // Gentle smoothing, so the flight still follows the branch: shortcut at most
    // a few nodes ahead, then round the corners
    var smooth = [path[0]], i0 = 0;
    while (i0 < path.length - 1) {
      var j = Math.min(path.length - 1, i0 + 4);
      while (j > i0 + 1 && !ok(path[i0], path[j])) j--;
      smooth.push(path[j]); i0 = j;
    }
    for (var pass = 0; pass < 2; pass++) {
      var r = [smooth[0]];
      for (var m = 0; m < smooth.length - 1; m++) {
        var p0 = smooth[m], p1 = smooth[m + 1];
        r.push({ x: 0.75 * p0.x + 0.25 * p1.x, y: 0.75 * p0.y + 0.25 * p1.y }, { x: 0.25 * p0.x + 0.75 * p1.x, y: 0.25 * p0.y + 0.75 * p1.y });
      }
      r.push(smooth[smooth.length - 1]); smooth = r;
    }
    return { route: smooth, goal: goal, branch: path, search: { kind: "edges", items: edges } };
  }

  function planExplore(t) {
    var R = 60, seen = new Uint8Array(t.w * t.h);
    var region = function (gx, gy) { var c = t.centre(gx, gy); return c.x > ax(0.42) && inView(c, 10); };
    var total = 0; for (var gy = 0; gy < t.h; gy++) for (var gx = 0; gx < t.w; gx++) if (region(gx, gy)) total++;
    function look(p) {
      var c = t.toCell(p), r = Math.ceil(R / t.cell), count = 0;
      for (var dy = -r; dy <= r; dy++) for (var dx = -r; dx <= r; dx++) {
        var x = c.gx + dx, y = c.gy + dy;
        if (x < 0 || y < 0 || x >= t.w || y >= t.h || dx * dx + dy * dy > r * r) continue;
        var i = t.idx(x, y); if (!seen[i] && region(x, y)) count++; seen[i] = 1;
      }
      return count;
    }
    // local relief (max minus min within a few cells): rugged ground is more interesting to look at
    var relief = new Float32Array(t.w * t.h), rr = 3, zr = 1e-6;
    for (gy = 0; gy < t.h; gy++) for (gx = 0; gx < t.w; gx++) {
      var lo = Infinity, hi = -Infinity;
      for (var ry = -rr; ry <= rr; ry++) for (var rx = -rr; rx <= rr; rx++) {
        var xx = gx + rx, yy = gy + ry; if (xx < 0 || yy < 0 || xx >= t.w || yy >= t.h) continue;
        var zz = t.z[t.idx(xx, yy)]; if (zz < lo) lo = zz; if (zz > hi) hi = zz;
      }
      relief[t.idx(gx, gy)] = hi - lo; if (hi - lo > zr) zr = hi - lo;
    }
    var pos = { x: HOME.x, y: HOME.y }, route = [pos], covered = look(pos);
    for (var stepN = 0; stepN < 160 && covered < 0.93 * total; stepN++) {
      // next target: the unseen cell with the best ruggedness for its distance
      var target = -1, best = -Infinity;
      for (var i = 0; i < seen.length; i++) {
        var x = i % t.w; if (seen[i] || !region(x, Math.floor(i / t.w))) continue;
        var c = t.centre(x, Math.floor(i / t.w));
        var score = (0.25 + relief[i] / zr) / (40 + dist(pos, c));
        if (score > best) { best = score; target = i; }
      }
      if (target < 0) break;
      var tp = t.centre(target % t.w, Math.floor(target / t.w));
      // move towards it in sensor-sized hops, looking as we go
      var hops = Math.max(1, Math.ceil(dist(pos, tp) / (R * 0.8)));
      for (var hN = 1; hN <= hops; hN++) {
        var p = { x: pos.x + ((tp.x - pos.x) * hN) / hops, y: pos.y + ((tp.y - pos.y) * hN) / hops };
        covered += look(p); route.push(p);
      }
      pos = tp;
    }
    route.push(HOME);
    return { route: roundCorners(route, R * 0.7).pts, reveal: R, spacing: 1.1 * R }; // bank round each change of target
  }

  // Expanding square: the search-and-rescue pattern, spiralling out from a datum
  function planSquare(t) {
    var s = 100, x0 = ax(0.45), x1 = VIEW.x1 - 24, y0 = VIEW.y0 + 24, y1 = VIEW.y1 - 24; // track spacing; sensor views overlap it
    var datum = { x: ax(0.72) + (Math.random() - 0.5) * 80, y: vy(0.48) + (Math.random() - 0.5) * 60 };
    var pts = [HOME, datum], p = { x: datum.x, y: datum.y }, dirs = [[0, -1], [1, 0], [0, 1], [-1, 0]];
    for (var i = 0; i < 60; i++) {
      var len = s * Math.ceil((i + 1) / 2), dx = dirs[i % 4][0], dy = dirs[i % 4][1];
      var q = { x: p.x + dx * len, y: p.y + dy * len }, clipped = false;
      if (q.x < x0 || q.x > x1 || q.y < y0 || q.y > y1) { // stop at the edge of the search area
        q = { x: Math.max(x0, Math.min(x1, q.x)), y: Math.max(y0, Math.min(y1, q.y)) }; clipped = true;
      }
      pts.push(q); p = q;
      if (clipped) break;
    }
    pts.push(HOME);
    var round = roundCorners(pts, 40), legs = pts.length;
    return withSensor({ route: round.pts, goal: datum, speed: 170,
             shootable: function (i) { var j = round.leg[i]; return j >= 2 && j <= legs - 2; } }, s); // no looks on the legs out and home
  }

  // Contour survey: fly the land's own contour lines, section by section, nearest next
  function planContour(t, contours) {
    var inRegion = function (q) { return q.x >= ax(0.47) && inView(q, 20); };
    var lines = [];
    contours.forEach(function (path) { // decode the compact relative path data
      path.getAttribute("d").split("M").forEach(function (chunk) {
        var n = chunk.match(/-?\d+/g); if (!n || n.length < 6) return;
        var x = +n[0], y = +n[1], line = [{ x: x, y: y }];
        for (var k = 2; k + 1 < n.length; k += 2) { x += +n[k]; y += +n[k + 1]; line.push({ x: x, y: y }); }
        var run = [], bestRun = []; // longest stretch of the line inside the survey area
        line.forEach(function (q) { if (inRegion(q)) run.push(q); else { if (run.length > bestRun.length) bestRun = run; run = []; } });
        if (run.length > bestRun.length) bestRun = run;
        var len = 0; for (var m = 1; m < bestRun.length; m++) len += dist(bestRun[m - 1], bestRun[m]);
        if (len < 180) return;
        var z = 0; bestRun.forEach(function (q) { z += t.at(q); });
        lines.push({ pts: bestRun, len: len, z: z / bestRun.length });
      });
    });
    if (!lines.length) return planLawnmower(t);
    // Coverage-driven choice: take lines (longest first) while they mostly cover
    // ground no chosen line's camera swath has seen yet
    var swath = 110, covered = new Uint8Array(t.w * t.h), r = Math.ceil(swath / 2 / t.cell), chosen = [];
    function cellOf(q) { return t.toCell(q); }
    lines.sort(function (a, b) { return b.len - a.len; });
    lines.forEach(function (l) {
      if (chosen.length >= 14) return;
      var fresh = 0;
      l.pts.forEach(function (q) { var c = cellOf(q); if (!covered[t.idx(c.gx, c.gy)]) fresh++; });
      if (fresh / l.pts.length < 0.6) return; // mostly overlaps lines already chosen
      chosen.push(l);
      l.pts.forEach(function (q) {
        var c = cellOf(q);
        for (var dy = -r; dy <= r; dy++) for (var dx = -r; dx <= r; dx++) {
          var x = c.gx + dx, y = c.gy + dy;
          if (x >= 0 && y >= 0 && x < t.w && y < t.h && dx * dx + dy * dy <= r * r) covered[t.idx(x, y)] = 1;
        }
      });
    });
    var route = [HOME], pos = HOME, transit = {};
    // The stored contours step in whole units and zigzag; the drone flies an evened-out version of each
    // (the map still shows the real lines), and curves onto the next line from its current heading
    function smooth(pts) {
      var even = [pts[0]], step = 8, carry = 0;
      for (var i = 1; i < pts.length; i++) { // resample at even spacing
        var a = pts[i - 1], b = pts[i], seg = dist(a, b), u = step - carry;
        for (; u <= seg; u += step) even.push({ x: a.x + (b.x - a.x) * u / seg, y: a.y + (b.y - a.y) * u / seg });
        carry = seg - (u - step);
      }
      even.push(pts[pts.length - 1]);
      for (var pass = 0; pass < 12; pass++) { // average each point with its neighbours, ends fixed
        even = even.map(function (q, k) {
          if (!k || k === even.length - 1) return q;
          return { x: (even[k - 1].x + 2 * q.x + even[k + 1].x) / 4, y: (even[k - 1].y + 2 * q.y + even[k + 1].y) / 4 };
        });
      }
      return even;
    }
    function hop(to) { // a gentle curve from the drone's heading onto the next line
      var prev = route.length > 1 ? route[route.length - 2] : { x: pos.x, y: pos.y + 1 }, d = dist(pos, to); // take-off heads up
      if (d < 30) return;
      var hd = dist(prev, pos) || 1, k = Math.min(70, d / 2);
      var c = { x: pos.x + (pos.x - prev.x) / hd * k, y: pos.y + (pos.y - prev.y) / hd * k };
      for (var j = 1; j < 8; j++) {
        var u = j / 8, w = 1 - u;
        transit[route.length] = true;
        route.push({ x: w * w * pos.x + 2 * w * u * c.x + u * u * to.x, y: w * w * pos.y + 2 * w * u * c.y + u * u * to.y });
      }
    }
    // Fly the lines a section at a time, always moving on to the nearest unflown section (from either end),
    // so the drone works across the ground in short hops, up and down the levels, rather than finishing one
    // level and crossing the screen to start the next
    var sections = [];
    chosen.forEach(function (l) {
      var pts = smooth(l.pts), cut = [pts[0]], run = 0;
      for (var i = 1; i < pts.length; i++) {
        run += dist(pts[i - 1], pts[i]); cut.push(pts[i]);
        if (run >= 200 && pts.length - i > 12) { sections.push(cut); cut = [pts[i]]; run = 0; }
      }
      if (cut.length > 1) sections.push(cut);
    });
    var order = [], at = HOME;
    while (sections.length) {
      var best = 0, flip = false, bestD = Infinity;
      sections.forEach(function (sec, i) {
        var a = dist(at, sec[0]), b = dist(at, sec[sec.length - 1]);
        if (a < bestD) { bestD = a; best = i; flip = false; }
        if (b < bestD) { bestD = b; best = i; flip = true; }
      });
      var sec = sections.splice(best, 1)[0];
      if (flip) sec = sec.slice().reverse();
      order.push(sec); at = sec[sec.length - 1];
    }
    // Then untangle (2-opt): reverse any run of sections whose reversal shortens the hops, counting the
    // flight home, so the route loops round and finishes near home instead of crossing back over the screen
    function first(k) { return k < 0 || k >= order.length ? HOME : order[k][0]; }
    function last(k) { return k < 0 || k >= order.length ? HOME : order[k][order[k].length - 1]; }
    function untangle() {
      for (var tries = 0, better = true; better && tries < 50; tries++) {
        better = false;
        for (var a = 0; a < order.length - 1; a++) for (var b = a + 1; b < order.length; b++) {
          var before = dist(last(a - 1), first(a)) + dist(last(b), first(b + 1));
          var after = dist(last(a - 1), last(b)) + dist(first(a), first(b + 1));
          if (after < before - 1) {
            order = order.slice(0, a).concat(order.slice(a, b + 1).reverse().map(function (q) { return q.slice().reverse(); }), order.slice(b + 1));
            better = true;
          }
        }
      }
    }
    function secLen(q) { var L = 0; for (var i = 1; i < q.length; i++) L += dist(q[i - 1], q[i]); return L; }
    untangle();
    // Skip small stray sections that would need a long hop across the screen: drop the shorter section beside
    // the longest such hop, re-untangle, and repeat (the dim contours still show there; only the drone's visit
    // is skipped). Big sections stay even if a longer hop reaches them. Take-off and the flight home aren't counted.
    for (var cuts = order.length; cuts > 0 && order.length > 3; cuts--) {
      var worst = -1, worstD = 180;
      for (var k = 1; k < order.length; k++) {
        var dk = dist(last(k - 1), first(k));
        if (dk > worstD && Math.min(secLen(order[k - 1]), secLen(order[k])) < 260) { worstD = dk; worst = k; } // only small strays go
      }
      if (worst < 0) break;
      order.splice(secLen(order[worst - 1]) < secLen(order[worst]) ? worst - 1 : worst, 1);
      untangle();
    }
    order.forEach(function (pts) {
      hop(pts[0]);
      transit[route.length] = true; // the hop onto this section ends at its first point
      route = route.concat(pts); pos = pts[pts.length - 1];
    });
    hop(HOME);
    transit[route.length] = true; // and the flight home
    route.push(HOME);
    return withSensor({ route: route, speed: 220, shootable: function (i) { return !transit[i]; } }, swath / 1.2);
  }

  // Multi-drone partition: k-means zones, then each drone sweeps its own
  function planPartition(t) {
    var k = 3, x0 = ax(0.5), x1 = ax(0.95), y0 = vy(0.16), y1 = vy(0.9), gap = 70;
    var cells = [];
    for (var gy = 0; gy < t.h; gy++) for (var gx = 0; gx < t.w; gx++) {
      var c = t.centre(gx, gy); if (c.x >= x0 && c.x <= x1 && c.y >= y0 && c.y <= y1) cells.push(c);
    }
    var seeds = [];
    for (var i = 0; i < k; i++) { var c0 = cells[Math.floor(Math.random() * cells.length)]; seeds.push({ x: c0.x, y: c0.y }); }
    var label = new Int8Array(cells.length);
    for (var it = 0; it < 10; it++) { // k-means on cell centres
      cells.forEach(function (c, j) { var b = 0, bd = Infinity; seeds.forEach(function (s, m) { var d = dist(c, s); if (d < bd) { bd = d; b = m; } }); label[j] = b; });
      seeds = seeds.map(function (s, m) { var sx = 0, sy = 0, n = 0; cells.forEach(function (c, j) { if (label[j] === m) { sx += c.x; sy += c.y; n++; } }); return n ? { x: sx / n, y: sy / n } : s; });
    }
    function zoneAt(q) { var b = 0, bd = Infinity; seeds.forEach(function (s, m) { var d = dist(q, s); if (d < bd) { bd = d; b = m; } }); return b; }
    var routes = [];
    for (var m = 0; m < k; m++) {
      var pts = [HOME], flip = false;
      for (var y = y0 + gap / 2; y <= y1; y += gap) { // sweep rows, keeping the stretches inside this zone
        var runs = [], runStart = null;
        for (var x = x0; x <= x1 + 4; x += 4) { // one step past the edge closes any open stretch
          var inside = x <= x1 && zoneAt({ x: x, y: y }) === m;
          if (inside && runStart === null) runStart = x;
          if (!inside && runStart !== null) { runs.push([runStart, x - 4]); runStart = null; }
        }
        if (flip) runs.reverse();
        runs.forEach(function (r) { var a = flip ? r[1] : r[0], b = flip ? r[0] : r[1]; if (Math.abs(b - a) > 8) pts.push({ x: a, y: y }, { x: b, y: y }); });
        if (runs.length) flip = !flip;
      }
      pts.push(HOME);
      var round = roundCorners(pts, gap / 2); // smooth U-turns between passes
      routes.push({ pts: round.pts, leg: round.leg, legs: pts.length });
    }
    var zones = cells.map(function (c) { var z = zoneAt(c); return { x: c.x, y: c.y, k: z, d: dist(c, seeds[z]) }; });
    zones.sort(function (a, b) { return a.d - b.d; }); // zones grow outwards from their centres
    return withSensor({ routes: routes, speed: 150, search: { kind: "zones", items: zones },
             shootable: function (i, n, r) { var j = r.leg[i]; return j >= 2 && j <= r.legs - 2; } }, gap); // no looks on the legs out and home
  }

  var PLANNERS = { lawnmower: planLawnmower, astar: planAstar, rrt: planRRT, explore: planExplore,
                   square: planSquare, contour: planContour, partition: planPartition };

  // ── data ────────────────────────────────────────────────────────────────
  var cache = {};
  function load(base, slug) {
    if (cache[slug]) return cache[slug];
    function get(url, type) { return fetch(url).then(function (r) { if (!r.ok) throw new Error(r.status); return r[type](); }); }
    cache[slug] = Promise.all([get(base + slug + ".svg", "text"), get(base + "grid/" + slug + ".json", "json")]).then(function (res) {
      var doc = new DOMParser().parseFromString(res[0], "image/svg+xml");
      var contours = Array.prototype.slice.call(doc.documentElement.querySelectorAll("path"));
      if (!contours.length) throw new Error("no contours");
      return { contours: contours, terrain: new Terrain(res[1]) };
    });
    cache[slug].catch(function () { delete cache[slug]; });
    return cache[slug];
  }

  // ── engine: one per SVG ─────────────────────────────────────────────────
  var engines = 0;
  function polyD(pts) { return "M" + pts.map(function (p) { return p.x.toFixed(1) + " " + p.y.toFixed(1); }).join(" L"); }
  function routesOf(plan) { return plan.routes || [{ pts: plan.route }]; }
  function later(fn) { requestAnimationFrame(function () { requestAnimationFrame(fn); }); } // after first paint, so transitions run

  // Three stacked SVGs share the box: the background (this.svg), the terrain,
  // and the routes and drones on top. The terrain and top layers drift as whole
  // elements, which browsers move on the GPU, and each drone frame redraws only
  // the light top layer: Safari repaints SVG on the CPU, so one SVG holding the
  // contours, the reveal mask and the drone stuttered there.
  function Engine(svg) {
    this.svg = svg; this.id = "cp-rt" + ++engines; this.run = 0; this.scene = null;
    var cls = svg.getAttribute("class") || "";
    function layer(kind) {
      return el("svg", { class: cls + " cp-rt-layer cp-rt-drift cp-rt-" + kind, viewBox: svg.getAttribute("viewBox"),
        preserveAspectRatio: svg.getAttribute("preserveAspectRatio"), "aria-hidden": "true", focusable: "false" });
    }
    this.ground = layer("ground"); this.top = layer("top");
    svg.after(this.ground, this.top);
  }

  // Draw the terrain and overlays for a plan. terrainFrom: starting opacity of
  // the contours (0 after a terrain fade, 0.22 coming from a coverage route).
  Engine.prototype.build = function (data, plan, terrainFrom) {
    var svg = this.svg, id = this.id, ground = this.ground, top = this.top;
    svg.replaceChildren(); ground.replaceChildren(); top.replaceChildren();
    var defs = el("defs", {}, ground);
    var grad = el("radialGradient", { id: id + "-bg", cx: "75%", cy: "40%", r: "90%" }, el("defs", {}, svg));
    el("stop", { offset: "0", "stop-color": "#1b3a5c" }, grad);
    el("stop", { offset: ".6", "stop-color": "#10233a" }, grad);
    el("stop", { offset: "1", "stop-color": "#0a1726" }, grad);
    el("rect", { width: W, height: H, fill: "url(#" + id + "-bg)" }, svg);
    var scene = { plan: plan };
    var terrain = el("g", { class: "cp-rt-terrain" }, ground);
    var layer = el("g", { class: "cp-contours" }, terrain);
    data.contours.forEach(function (p) { layer.appendChild(p.cloneNode(true)); });
    if (plan.reveal) { // coverage: dim everything, then reveal full-strength contours one sensor look at a time
      layer.setAttribute("opacity", "0.22");
      // Each look shows this copy through its own small circular clip (see look below). One growing mask
      // made Safari redraw the whole revealed copy, across the hero, every time a look was added.
      var full = el("g", { id: id + "-full", class: "cp-contours" }, defs);
      data.contours.forEach(function (p) { full.appendChild(p.cloneNode(true)); });
      scene.defs = defs;
      scene.reveal = el("g", { class: "cp-contours" }, terrain);
      scene.looks = 0;
    }
    // fade the terrain in: from nothing, or (point-to-point after coverage) from dim to full
    if (terrainFrom != null && !reduced) {
      if (plan.reveal || terrainFrom === 0) { terrain.style.opacity = 0; later(function () { terrain.style.opacity = ""; }); }
      else { layer.style.opacity = terrainFrom; later(function () { layer.style.opacity = ""; }); }
    }
    var over = el("g", { class: "cp-rt-overlay" }, top);
    if (plan.nogo) el("path", { class: "cp-lab-nogo", d: plan.nogo.map(function (c) { return "M" + (c.x - 4) + " " + (c.y - 4) + "h8v8h-8z"; }).join("") }, over);
    scene.search = el("g", { class: "cp-lab-search" }, over);
    if (plan.branch) {
      scene.branch = el("path", { class: "cp-lab-branch", d: polyD(plan.branch.slice().reverse()) }, over); // traced from the goal back
      scene.branchLen = scene.branch.getTotalLength();
      scene.branch.style.strokeDasharray = scene.branchLen; scene.branch.style.strokeDashoffset = scene.branchLen;
    }
    scene.frames = el("g", { class: "cp-frames" }, over);
    scene.flights = routesOf(plan).map(function (r, i) {
      var tint = i ? " cp-lab-tint--" + i : "";
      // the trail is rebuilt from the points actually flown, so nothing ahead of the drone is drawn
      var path = el("path", { class: "cp-route cp-lab-trail" + tint, d: "" }, over);
      var cum = [0];
      for (var k = 1; k < r.pts.length; k++) cum.push(cum[k - 1] + dist(r.pts[k - 1], r.pts[k]));
      return { route: r, path: path, pts: r.pts, cum: cum, len: cum[cum.length - 1], tint: tint, nextShot: 0, at: 1, doneTo: 0, doneD: "" };
    });
    el("circle", { class: "cp-home", cx: HOME.x, cy: HOME.y, r: 7 }, over);
    if (plan.goal) el("circle", { class: "cp-lab-goal", cx: plan.goal.x, cy: plan.goal.y, r: 9 }, over);
    scene.flights.forEach(function (f) {
      var drone = el("g", { class: "cp-drone" + f.tint }, over);
      el("circle", { class: "cp-drone__halo", r: 20 }, drone);
      el("path", { class: "cp-drone__arm", d: "M-11,-11 L11,11 M11,-11 L-11,11" }, drone);
      [[-11, -11], [11, -11], [-11, 11], [11, 11]].forEach(function (c) { el("circle", { class: "cp-drone__rotor", cx: c[0], cy: c[1], r: 6.5 }, drone); });
      el("rect", { class: "cp-drone__body", x: -5, y: -5, width: 10, height: 10, rx: 2 }, drone);
      f.drone = drone;
    });
    scene.terrain = terrain; scene.over = over;
    this.scene = scene;
    return scene;
  };

  // Plan and fly one route; onDone fires when the flight ends (not in reduced motion)
  Engine.prototype.play = function (data, algo, terrainFrom, onDone) {
    var myRun = ++this.run, self = this;
    setView(this.svg); // plan within what's on screen
    var t0p = performance.now(), plan = PLANNERS[algo](data.terrain, data.contours), ms = performance.now() - t0p;
    var scene = this.build(data, plan, terrainFrom);
    var flights = scene.flights;
    function pointAt(f, d, from) { // position after flying distance d along the route (searching on from a known leg)
      var i = from || 1;
      while (i < f.cum.length - 1 && f.cum[i] < d) i++;
      var a = f.pts[i - 1], b = f.pts[i], seg = f.cum[i] - f.cum[i - 1], u = seg ? (d - f.cum[i - 1]) / seg : 0;
      u = Math.max(0, Math.min(1, u));
      return { x: a.x + (b.x - a.x) * u, y: a.y + (b.y - a.y) * u, i: i };
    }
    function trail(f, d) { // the flown legs are kept as a string; each frame only adds the drone's current point
      var p = pointAt(f, d, f.at);
      f.at = p.i;
      for (; f.doneTo < p.i; f.doneTo++) f.doneD += (f.doneTo ? " L" : "M") + f.pts[f.doneTo].x.toFixed(1) + " " + f.pts[f.doneTo].y.toFixed(1);
      f.path.setAttribute("d", f.doneD + " L" + p.x.toFixed(1) + " " + p.y.toFixed(1));
      return p;
    }
    function place(f, p) { f.drone.setAttribute("transform", "translate(" + p.x.toFixed(1) + " " + p.y.toFixed(1) + ")"); }
    var speed = plan.speed || (algo === "lawnmower" ? 190 : algo === "explore" ? 210 : 120); // viewBox units per second
    var longest = Math.max.apply(null, flights.map(function (f) { return f.len; }));
    var searchDur = plan.search ? (reduced ? 0 : { cells: 1800, edges: 3000, zones: 2200 }[plan.search.kind] || 2500) : 0;
    var flightDur = (longest / speed) * 1000;
    var traceDur = scene.branch && !reduced ? 900 : 0; // light up the winning branch before take-off
    var spacing = plan.spacing || 64; // distance between sensor looks
    var searchDrawn = 0, items = plan.search ? plan.search.items : [];
    var fadesAfter = plan.search && (plan.search.kind === "zones" || plan.search.kind === "edges"); // zones at take-off; the tree once its branch is found
    function drawSearch(upTo) {
      var kind = plan.search && plan.search.kind, groups = {};
      for (; searchDrawn < upTo; searchDrawn++) {
        var it = items[searchDrawn], cls, d;
        if (kind === "cells") { cls = "cp-lab-cells"; d = "M" + (it.x - 3) + " " + (it.y - 3) + "h6v6h-6z"; }
        else if (kind === "zones") { cls = "cp-lab-zone cp-lab-zone--" + it.k; d = "M" + (it.x - 4) + " " + (it.y - 4) + "h8v8h-8z"; }
        else { cls = "cp-lab-tree"; d = "M" + it[0].x.toFixed(1) + " " + it[0].y.toFixed(1) + "L" + it[1].x.toFixed(1) + " " + it[1].y.toFixed(1); }
        (groups[cls] || (groups[cls] = [])).push(d);
      }
      for (var c in groups) el("path", { d: groups[c].join(""), class: c }, scene.search);
    }
    function look(p, f) {
      if (!plan.reveal) return; // point-to-point routes: no sensing
      if (plan.survey && !plan.survey(p)) return; // lawnmower: only over the survey block
      if (dist(p, HOME) < 30) return; // not on the ground at take-off
      if (plan.shootable && !plan.shootable(p.i, f.pts.length, f.route)) return; // transit legs: no looks
      var clip = el("clipPath", { id: self.id + "-look" + scene.looks++ }, scene.defs);
      el("circle", { cx: p.x, cy: p.y, r: plan.reveal }, clip);
      el("use", { href: "#" + self.id + "-full", "clip-path": "url(#" + clip.id + ")" }, scene.reveal);
      if (reduced) return;
      var ring = el("circle", { class: "cp-lab-ring" + f.tint, cx: p.x, cy: p.y, r: plan.reveal }, scene.frames); // fades out in CSS
      setTimeout(function () { ring.remove(); }, 1600);
    }
    if (reduced) { // finished state, no motion
      drawSearch(items.length);
      if (fadesAfter) scene.search.classList.add("is-faded");
      if (scene.branch) scene.branch.style.strokeDashoffset = 0;
      flights.forEach(function (f) { for (var d = 0; d <= f.len; d += spacing) look(pointAt(f, d), f); place(f, trail(f, f.len)); });
      return { plan: plan, ms: ms };
    }
    var t0 = performance.now();
    function frame(now) {
      if (myRun !== self.run) return;
      var t = now - t0;
      if (t < searchDur) { // the planner "thinking"
        drawSearch(Math.floor((t / searchDur) * items.length));
        flights.forEach(function (f) { place(f, f.pts[0]); });
        return requestAnimationFrame(frame);
      }
      drawSearch(items.length);
      if (fadesAfter) scene.search.classList.add("is-faded");
      if (t < searchDur + traceDur) {
        scene.branch.style.strokeDashoffset = scene.branchLen * (1 - (t - searchDur) / traceDur);
        return requestAnimationFrame(frame);
      }
      if (scene.branch) scene.branch.style.strokeDashoffset = 0;
      var progress = Math.min(1, (t - searchDur - traceDur) / flightDur) * longest; // every drone flies at the same speed
      flights.forEach(function (f) {
        var d = Math.min(progress, f.len);
        place(f, trail(f, d));
        while (f.nextShot <= d) { look(pointAt(f, f.nextShot), f); f.nextShot += spacing; }
      });
      if (progress < longest) return requestAnimationFrame(frame);
      if (onDone) onDone();
    }
    requestAnimationFrame(frame);
    return { plan: plan, ms: ms };
  };

  Engine.prototype.stop = function () { this.run++; };

  // Fade out the routes (and the terrain too, if asked), then call back
  Engine.prototype.fadeOut = function (withTerrain, done) {
    var s = this.scene, myRun = this.run;
    if (!s || reduced) return done();
    s.over.style.opacity = 0;
    if (withTerrain) s.terrain.style.opacity = 0;
    var self = this;
    setTimeout(function () { if (myRun === self.run) done(); }, 1000);
  };

  window.CopterRoutes = { ALGOS: ALGOS, load: load, Engine: Engine, reduced: reduced };

  // ── menu: a small accessible dropdown that opens upwards over the hero ──
  // Native select pop-ups can't be styled or placed, so this is a button plus
  // a listbox: arrow keys, Home/End, Enter or Space to choose, Escape to close.
  function Menu(host, label, items, onPick) {
    var self = this;
    this.items = items; this.onPick = onPick; this.value = null;
    host.classList.add("cp-dd");
    this.button = document.createElement("button");
    this.button.type = "button";
    this.button.className = "cp-dd__button";
    this.button.setAttribute("aria-haspopup", "listbox");
    this.button.setAttribute("aria-expanded", "false");
    this.button.setAttribute("aria-label", label);
    this.text = document.createElement("span");
    this.text.className = "cp-dd__text";
    this.button.append(this.text);
    this.list = document.createElement("ul");
    this.list.className = "cp-dd__list";
    this.list.setAttribute("role", "listbox");
    this.list.setAttribute("aria-label", label);
    this.list.hidden = true;
    items.forEach(function (it) {
      var li = document.createElement("li");
      li.className = "cp-dd__option"; li.setAttribute("role", "option"); li.tabIndex = -1;
      li.textContent = it.label; li.dataset.value = it.value;
      if (it.title) li.title = it.title;
      li.addEventListener("click", function () { self.choose(it.value); });
      self.list.append(li);
      it.el = li;
    });
    host.append(this.list, this.button);
    this.button.addEventListener("click", function () { self.list.hidden ? self.open() : self.close(); });
    this.button.addEventListener("keydown", function (e) {
      if (e.key === "ArrowUp" || e.key === "ArrowDown") { e.preventDefault(); self.open(); }
    });
    this.list.addEventListener("keydown", function (e) {
      var opts = self.items.map(function (it) { return it.el; }), i = opts.indexOf(document.activeElement);
      if (e.key === "ArrowDown") { e.preventDefault(); opts[Math.min(opts.length - 1, i + 1)].focus(); }
      else if (e.key === "ArrowUp") { e.preventDefault(); opts[Math.max(0, i - 1)].focus(); }
      else if (e.key === "Home") { e.preventDefault(); opts[0].focus(); }
      else if (e.key === "End") { e.preventDefault(); opts[opts.length - 1].focus(); }
      else if (e.key === "Enter" || e.key === " ") { e.preventDefault(); if (i >= 0) self.choose(self.items[i].value); }
      else if (e.key === "Escape" || e.key === "Tab") { self.close(e.key === "Escape"); }
    });
    document.addEventListener("click", function (e) { if (!host.contains(e.target)) self.close(); });
  }
  Menu.prototype.set = function (value) {
    this.value = value;
    var it = this.items.filter(function (x) { return x.value === value; })[0];
    if (!it) return;
    this.text.textContent = it.label;
    this.button.title = it.title || it.label;
    this.items.forEach(function (x) { x.el.setAttribute("aria-selected", x.value === value ? "true" : "false"); });
  };
  Menu.prototype.open = function () {
    this.list.hidden = false; this.button.setAttribute("aria-expanded", "true");
    var sel = this.items.filter(function (x) { return x.value === this.value; }, this)[0];
    (sel ? sel.el : this.items[0].el).focus();
    if (sel) sel.el.scrollIntoView({ block: "nearest" });
  };
  Menu.prototype.close = function (refocus) {
    if (this.list.hidden) return;
    this.list.hidden = true; this.button.setAttribute("aria-expanded", "false");
    if (refocus) this.button.focus();
  };
  Menu.prototype.choose = function (value) { this.close(true); this.set(value); this.onPick(value); }; // re-picking the current one replays it

  // ── home page hero ──────────────────────────────────────────────────────
  // Terrain: random on load, kept until a full refresh.
  // Route: random; after each flight, pause, fade, and pick a different one.
  // The route menu always shows what is flying; picking one plays it next.
  var art = document.querySelector(".cp-hero__art");
  var credit = document.querySelector(".cp-hero__credit");
  if (!art || !credit || !window.CP_TERRAIN || !window.fetch || !window.DOMParser) return;
  var base = window.CP_TERRAIN_BASE || "assets/terrain/";
  var places = window.CP_TERRAIN, engine = new Engine(art);
  var mapLink = credit.querySelector(".cp-hero__map"), dataSpan = credit.querySelector(".cp-hero__data");
  var place = pick(places), algo = null, timer = null;

  var routeMenu = new Menu(credit.querySelector('[data-hero="route"]'), "Flight route",
    Object.keys(ALGOS).map(function (k) { return { value: k, label: ALGOS[k].label, title: ALGOS[k].text }; }),
    function (k) { restart(k); });

  function link(a, href, text, title) {
    a.href = href; a.textContent = text; a.target = "_blank"; a.rel = "noopener";
    if (title) a.title = title;
    a.classList.add("cp-hero__ext"); // external link: arrow added in CSS
  }
  function showCredit() {
    link(mapLink, place.map, place.place, "Show on OpenStreetMap");
    dataSpan.replaceChildren();
    place.sources.forEach(function (source, i) {
      if (i) dataSpan.append(", ");
      var a = document.createElement("a");
      link(a, source.url, source.name, source.title);
      dataSpan.append(a);
    });
  }
  function nextAlgo() { return pick(Object.keys(ALGOS).filter(function (k) { return k !== algo; })); }

  // Play a route (the given one, or a random different one) on the current terrain
  function playNext(terrainFrom, forced) {
    clearTimeout(timer);
    var next = forced || nextAlgo();
    load(base, place.slug).then(function (data) {
      algo = next;
      routeMenu.set(algo);
      engine.play(data, algo, terrainFrom, function () {
        timer = setTimeout(function () { // pause, fade, then a different route on the same terrain
          var upcoming = nextAlgo(), fadeTerrain = ALGOS[upcoming].coverage;
          engine.fadeOut(fadeTerrain, function () {
            playNext(fadeTerrain ? 0 : ALGOS[algo].coverage ? 0.22 : 1, upcoming);
          });
        }, 3000);
      });
      showCredit();
      credit.hidden = false;
    }).catch(function () { /* keep the built-in fallback animation */ });
  }
  function restart(forced) { // a menu choice: fade everything, then start again
    engine.stop(); clearTimeout(timer);
    engine.fadeOut(true, function () { playNext(0, forced); });
  }
  playNext(0);
})();
